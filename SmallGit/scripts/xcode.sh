#!/usr/bin/env bash
# Generate SmallGit.xcodeproj and open it.
#
# Usage:
#   scripts/xcode.sh              # generate if needed, then open
#   scripts/xcode.sh --force      # rewrite project.yml and regenerate
#   scripts/xcode.sh --no-open    # generate only
#
# The project is generated rather than committed. Package.swift stays the one
# place sources and dependencies are declared — `swift build`, `swift test`
# and CI all still read it, and the generated project is a view onto the same
# sources for the things only Xcode does: Signing & Capabilities, Instruments,
# the debugger UI.
#
# project.yml is shared. A team picked in Xcode's Signing tab is preserved
# in the ignored generated project; --force never writes it into project.yml.
#
#   DEVELOPMENT_TEAM=YOUR_TEAM_ID scripts/xcode.sh --no-open
#
# ...seeds the team directly, which is what the Signing tab writes anyway.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PACKAGE_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${PACKAGE_ROOT}"

FORCE=0
OPEN_AFTER=1
for arg in "$@"; do
  case "$arg" in
    --force)   FORCE=1 ;;
    --no-open) OPEN_AFTER=0 ;;
    -h|--help)
      sed -n '2,21p' "${SCRIPT_DIR}/xcode.sh"
      exit 0 ;;
    *)
      echo "unknown option: $arg" >&2
      exit 2 ;;
  esac
done

if ! command -v xcodegen >/dev/null 2>&1; then
  echo "ERROR: xcodegen is not installed." >&2
  echo "       brew install xcodegen" >&2
  exit 1
fi

PROJECT_YML="${PACKAGE_ROOT}/project.yml"
PROJECT="${PACKAGE_ROOT}/SmallGit.xcodeproj"

# A team picked in Xcode's Signing tab is written to the .xcodeproj, not to
# project.yml — so --force would regenerate it away. Carry it over unless the
# caller is explicitly setting one.
if [[ -z "${DEVELOPMENT_TEAM+x}" && -f "${PROJECT}/project.pbxproj" ]]; then
  DEVELOPMENT_TEAM="$(sed -n 's/.*DEVELOPMENT_TEAM = \([A-Z0-9][A-Z0-9]*\);.*/\1/p' \
    "${PROJECT}/project.pbxproj" | sed -n '1p')"
  if [[ -n "${DEVELOPMENT_TEAM}" ]]; then
    echo "      keeping the signing team from the existing local project"
  fi
fi
# XcodeGen expands the literal placeholder in the shared YAML. An explicitly
# empty value clears the local team instead of importing the previous one.
export DEVELOPMENT_TEAM="${DEVELOPMENT_TEAM:-}"

if [[ ! -f "${PROJECT_YML}" || "${FORCE}" -eq 1 ]]; then
  echo "[1/2] writing project.yml"
  cat > "${PROJECT_YML}" <<YML
# Generated by scripts/xcode.sh — edit freely, it is not overwritten again
# unless you pass --force. Sources and dependencies mirror Package.swift,
# which stays the source of truth for swift build, swift test and CI.
name: SmallGit
options:
  bundleIdPrefix: one.vuba
  deploymentTarget:
    macOS: "14.0"
  createIntermediateGroups: true

settings:
  base:
    # Apple silicon only, matching \`swift build\`, which builds for the host
    # arch alone. Xcode would otherwise add an x86_64 slice to every Release
    # and Archive build — a universal binary is twice the size, and the two
    # build paths would quietly ship different products. Add x86_64 back here
    # if SmallGit ever needs to run on Intel Macs.
    ARCHS: arm64
    ONLY_ACTIVE_ARCH: NO

packages:
  Yams:
    url: https://github.com/jpsim/Yams.git
    from: 5.0.0

targets:
  SmallGit:
    type: application
    platform: macOS
    sources:
      - path: Sources/SmallGit
      # CFBundleIconFile names AppIcon, so the .icns has to land in
      # Contents/Resources — where build-app.sh copies it too.
      - path: Resources/AppIcon.icns
        buildPhase: resources
      - path: ../LICENSE
        buildPhase: resources
      - path: ../THIRD_PARTY_NOTICES.txt
        buildPhase: resources
    dependencies:
      - package: Yams
    settings:
      base:
        # The one Info.plist, shared with the SwiftPM build rather than
        # forked into a second copy that drifts.
        INFOPLIST_FILE: Info.plist
        GENERATE_INFOPLIST_FILE: NO
        PRODUCT_NAME: SmallGit
        PRODUCT_BUNDLE_IDENTIFIER: one.vuba.smallgit
        SWIFT_VERSION: "5.0"
        # Matches swiftSettings in Package.swift, so a file that compiles
        # here compiles there.
        OTHER_SWIFT_FLAGS: -enable-upcoming-feature StrictConcurrency -enable-upcoming-feature BareSlashRegexLiterals
        # Notarization requires the hardened runtime; harmless without it.
        ENABLE_HARDENED_RUNTIME: YES
        CODE_SIGN_STYLE: Automatic
        # Expanded by XcodeGen into the ignored project, never stored here.
        DEVELOPMENT_TEAM: \${DEVELOPMENT_TEAM}

  SmallGitTests:
    type: bundle.unit-test
    platform: macOS
    sources:
      - path: Tests/SmallGitTests
    dependencies:
      - target: SmallGit
    settings:
      base:
        SWIFT_VERSION: "5.0"
        OTHER_SWIFT_FLAGS: -enable-upcoming-feature StrictConcurrency -enable-upcoming-feature BareSlashRegexLiterals

schemes:
  SmallGit:
    build:
      targets:
        SmallGit: all
    run:
      config: Debug
    test:
      config: Debug
      targets:
        - SmallGitTests
YML
else
  echo "[1/2] reusing existing project.yml (--force to rewrite)"
fi

"${PACKAGE_ROOT}/../make_version.sh"

echo "[2/2] generating SmallGit.xcodeproj"
xcodegen generate --spec "${PROJECT_YML}" --project "${PACKAGE_ROOT}"

echo "OK: ${PROJECT}"
if [[ -z "${DEVELOPMENT_TEAM}" ]]; then
  echo "    No team set yet — pick one in the target's Signing & Capabilities"
  echo "    tab, or pass DEVELOPMENT_TEAM when running this script."
fi

if [[ "${OPEN_AFTER}" -eq 1 ]]; then
  exec xed "${PROJECT}"
fi
